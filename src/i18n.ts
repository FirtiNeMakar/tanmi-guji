export function translate(text: string, language: Language): string {
  return language === "ru" ? russian[text] ?? text : text;
}

export function readLanguage(): Language {
  try {
    return localStorage.getItem("tanmi-guji-language") === "ru" ? "ru" : "zh";
  } catch {
    return "zh";
  }
}
